#!/usr/bin/env python3
"""Write docs/reference/<group>.md, one page per group of areas, from the findings in data/<group>.json.

    python3 tools/reference.py

Each finding is one operation: method, path, status, purpose, params, body, answer, example, notes, evidence.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GROUPS = {
    "workflow": ("Workflow", "Tasks, requests, the cart, forms, workflows, teams, proxies, delegation and availability."),
    "catalog": ("Catalog", "Roles, resources, separation of duties, entitlements, categories, drivers and administrator assignments."),
    "people": ("People", "Users, groups, containers, entities, the organization chart, helpdesk and the DAL."),
    "settings": ("Settings", "The applications' configuration, administration, display, logging, caches and the workflow engines."),
    "unlisted": ("Not in the reference", "Routes the 4.10.2 server answers that the vendor's reference leaves out."),
}
STATUS = {
    "validated": "validated on the lab",
    "empty-on-lab": "answered on the lab, which had no data to show",
    "from-ui": "not run: worked out from the server's and the dashboard's code",
    "not-working": "did not work on the lab",
    "unknown": "not known yet",
}


def anchor(m, path):
    return re.sub(r"[^a-z0-9]+", "-", f"{m} {path}".lower()).strip("-")


def cell(v):
    return str(v if v is not None else "").replace("|", "\\|").replace("\n", " ")


def kind(k):
    return {"fixed": "fixed", "per-installation": "per installation", "free": ""}.get(k or "", k or "")


def section(f):
    out = [f'<a id="{anchor(f["method"], f["path"])}"></a>', f'### {f["method"]} `{f["path"]}`', ""]
    out += [f'{f.get("purpose", "").strip()}', "", f'**Status:** {STATUS.get(f["status"], f["status"])}. **Evidence:** {f.get("evidence", "")}.', ""]
    params = f.get("params") or []
    if params:
        out += ["| Parameter | In | Required | Accepted values | Kind |", "|---|---|---|---|---|"]
        for p in params:
            out.append(f'| `{cell(p.get("name"))}` | {cell(p.get("in"))} | {"yes" if p.get("required") else "no"} | {cell(p.get("values"))} | {kind(p.get("kind"))} |')
        out.append("")
    body = f.get("body") or {}
    if body.get("fields"):
        out += ["| Body field | Required | Accepted values | Kind |", "|---|---|---|---|"]
        for b in body["fields"]:
            req = b.get("required")
            out.append(f'| `{cell(b.get("name"))}` | {"yes" if req is True else "no" if req is False else cell(req)} | {cell(b.get("values"))} | {kind(b.get("kind"))} |')
        out.append("")
    if body.get("example") not in (None, {}, []):
        out += ["```json", json.dumps(body["example"], indent=2), "```", ""]
    for label, key in (("Answer", "answer"), ("Example", "example"), ("Notes", "notes")):
        if f.get(key):
            out += [f"**{label}:** {f[key]}", ""]
    return out


def main():
    os.makedirs(os.path.join(ROOT, "docs", "reference"), exist_ok=True)
    for g, (title, blurb) in GROUPS.items():
        src = os.path.join(ROOT, "data", f"{g}.json")
        if not os.path.exists(src):
            continue
        F = sorted(json.load(open(src)), key=lambda f: (f["path"].lower(), f["method"]))
        counts = {}
        for f in F:
            counts[f["status"]] = counts.get(f["status"], 0) + 1
        out = [f"# {title}", "", blurb, "",
               "Generated by `tools/reference.py` from `data/" + g + ".json`. Values marked **per installation** are",
               "examples from one lab: read them from your own system. See the [README](../../README.md#1-basics) for bases,",
               "signing in and errors.", "",
               "| Status | Operations |", "|---|---|"]
        out += [f"| {STATUS.get(s, s)} | {n} |" for s, n in sorted(counts.items(), key=lambda x: -x[1])]
        out += ["", "## Contents", ""]
        out += [f'- [{f["method"]} `{f["path"]}`](#{anchor(f["method"], f["path"])})' for f in F]
        out += ["", "## Operations", ""]
        for f in F:
            out += section(f)
        open(os.path.join(ROOT, "docs", "reference", f"{g}.md"), "w").write("\n".join(out).rstrip() + "\n")
        print(g, len(F))


if __name__ == "__main__":
    main()
